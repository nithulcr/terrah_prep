create or replace function public.create_free_subscription_for_profile()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_subscription public.subscriptions;
begin
  insert into public.subscriptions (user_id, plan_id, status, starts_at, expires_at)
  select new.id, p.id, 'active', now(), null
  from public.plans p
  where p.slug = 'free'
  on conflict do nothing
  returning * into v_subscription;

  if v_subscription.id is not null then
    insert into public.user_usage (user_id, subscription_id, subscription_started_at, subscription_expires_at)
    values (new.id, v_subscription.id, v_subscription.starts_at, v_subscription.expires_at)
    on conflict (user_id) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists profiles_create_free_subscription on public.profiles;
create trigger profiles_create_free_subscription
after insert on public.profiles
for each row execute function public.create_free_subscription_for_profile();

-- Backfill the FREE entitlement for profiles created before this migration.
insert into public.subscriptions (user_id, plan_id, status, starts_at, expires_at)
select pr.id, p.id, 'active', now(), null
from public.profiles pr
cross join public.plans p
where p.slug = 'free'
  and not exists (select 1 from public.subscriptions s where s.user_id = pr.id and s.status = 'active');

insert into public.user_usage (user_id, subscription_id, subscription_started_at, subscription_expires_at)
select s.user_id, s.id, s.starts_at, s.expires_at
from public.subscriptions s
where s.status = 'active'
on conflict (user_id) do nothing;

-- Call this from the payment webhook with the service role after marking the old
-- subscription non-active. It makes renewal resets atomic and database-driven.
create or replace function public.activate_subscription(
  p_user_id uuid,
  p_plan_slug text,
  p_started_at timestamptz default now()
)
returns public.subscriptions
language plpgsql
security definer
set search_path = public
as $$
declare
  v_plan public.plans;
  v_subscription public.subscriptions;
begin
  select * into v_plan from public.plans where slug = p_plan_slug and is_active;
  if not found then raise exception 'Active plan % does not exist', p_plan_slug using errcode = 'P0001'; end if;

  update public.subscriptions
  set status = case when status = 'active' then 'cancelled' else status end,
      cancelled_at = case when status = 'active' then now() else cancelled_at end
  where user_id = p_user_id and status = 'active';

  insert into public.subscriptions (user_id, plan_id, status, starts_at, expires_at)
  values (p_user_id, v_plan.id, 'active', p_started_at,
          case when v_plan.duration_days is null then null else p_started_at + make_interval(days => v_plan.duration_days) end)
  returning * into v_subscription;

  insert into public.user_usage (user_id, subscription_id, questions_today, tests_this_month,
                                 free_questions_used, last_daily_reset, subscription_started_at, subscription_expires_at)
  values (p_user_id, v_subscription.id, 0, 0, 0, current_date, v_subscription.starts_at, v_subscription.expires_at)
  on conflict (user_id) do update set subscription_id = excluded.subscription_id,
    questions_today = 0, tests_this_month = 0, last_daily_reset = current_date,
    subscription_started_at = excluded.subscription_started_at,
    subscription_expires_at = excluded.subscription_expires_at;
  return v_subscription;
end;
$$;

-- Schedule this function with Supabase Cron, or call it from a trusted scheduled job.
create or replace function public.expire_due_subscriptions()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare v_count integer;
begin
  with expired as (
    update public.subscriptions set status = 'expired'
    where status = 'active' and expires_at is not null and expires_at <= now()
    returning user_id
  )
  select count(*) into v_count from expired;

  -- Each affected profile receives a fresh FREE subscription and reset usage row.
  perform public.activate_subscription(pr.id, 'free')
  from public.profiles pr
  where not exists (select 1 from public.subscriptions s where s.user_id = pr.id and s.status = 'active');
  return v_count;
end;
$$;

-- Refreshes daily counters at login and returns the user's current entitlement.
create or replace function public.refresh_my_usage()
returns table (
  plan_slug text, daily_question_limit integer, monthly_mock_test_limit integer,
  lifetime_question_limit integer, questions_today integer, tests_this_month integer,
  free_questions_used integer, subscription_expires_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'Authentication required' using errcode = '28000'; end if;
  if exists (
    select 1 from public.subscriptions
    where user_id = auth.uid() and status = 'active'
      and expires_at is not null and expires_at <= now()
  ) then
    perform public.activate_subscription(auth.uid(), 'free');
  end if;
  update public.user_usage set questions_today = 0, last_daily_reset = current_date
  where user_id = auth.uid() and last_daily_reset < current_date;
  return query
  select p.slug, p.daily_question_limit, p.monthly_mock_test_limit, p.lifetime_question_limit,
         u.questions_today, u.tests_this_month, u.free_questions_used, u.subscription_expires_at
  from public.user_usage u
  join public.subscriptions s on s.id = u.subscription_id and s.status = 'active'
  join public.plans p on p.id = s.plan_id
  where u.user_id = auth.uid();
end;
$$;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.profiles where id = auth.uid() and role::text = 'admin') $$;

