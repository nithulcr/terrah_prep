-- The existing subscriptions table is kept as the subscription history. A user has
-- at most one active row; expiry moves that row to expired before FREE is activated.
alter table public.subscriptions
  add column if not exists starts_at timestamptz not null default now(),
  add column if not exists expires_at timestamptz,
  add column if not exists cancelled_at timestamptz,
  add column if not exists updated_at timestamptz not null default now();

alter table public.subscriptions alter column status set default 'active';
create unique index if not exists subscriptions_one_active_per_user_idx
  on public.subscriptions (user_id) where status = 'active';
create index if not exists subscriptions_user_status_expires_idx
  on public.subscriptions (user_id, status, expires_at);

create table if not exists public.user_usage (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  subscription_id bigint not null references public.subscriptions(id) on delete cascade,
  questions_today integer not null default 0 check (questions_today >= 0),
  tests_this_month integer not null default 0 check (tests_this_month >= 0),
  free_questions_used integer not null default 0 check (free_questions_used >= 0),
  last_daily_reset date not null default current_date,
  subscription_started_at timestamptz not null,
  subscription_expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id)
);

create index if not exists user_usage_subscription_id_idx on public.user_usage (subscription_id);

